// A validated case UUID in canonical lowercase hyphenated form.
///
/// Only real UUIDs are accepted. Names such as `CASE-026` are rejected, never mapped to an ID.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CaseId(String);

impl CaseId {
    /// Parses `raw` as a hyphenated UUID (`8-4-4-4-12` hex digits, any letter case).
    /// `option` names the CLI option for the error message.
    pub fn parse(raw: &str, option: &str) -> Result<Self, CliError> {
        let value = raw.trim();
        if is_hyphenated_uuid(value) {
            Ok(Self(value.to_ascii_lowercase()))
        } else {
            Err(CliError::InvalidArgument(format!(
                "{option} must be a case UUID such as 3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c, got {value:?}"
            )))
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// True for `xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx` with hex digits.
pub fn is_hyphenated_uuid(value: &str) -> bool {
    let bytes = value.as_bytes();
    bytes.len() == 36
        && bytes.iter().enumerate().all(|(i, b)| match i {
            8 | 13 | 18 | 23 => *b == b'-',
            _ => b.is_ascii_hexdigit(),
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn case_id_accepts_only_real_uuids() {
        let id = CaseId::parse(" 3F2B8C1E-7A4D-4E1B-9C3A-5D6E7F8A9B0C ", "--case").unwrap();
        assert_eq!(id.as_str(), "3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c");
        for bad in [
            "CASE-026",
            "case-026",
            "26",
            "",
            "3f2b8c1e7a4d4e1b9c3a5d6e7f8a9b0c",
            "{3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c}",
            "3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0g",
            "3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c/../x",
        ] {
            let err = CaseId::parse(bad, "--case").unwrap_err();
            assert_eq!(err.exit_code(), 2, "{bad}");
            assert!(err.to_string().contains("--case"), "{bad}");
        }
    }

    #[test]
    fn create_request_serializes_only_supplied_fields() {
        let minimal = CreateCaseRequest {
            title: "T".into(),
            description: None,
            fir_number: None,
            investigator_id: None,
            metadata: None,
            case_id: None,
        };
        assert_eq!(
            serde_json::to_value(&minimal).unwrap(),
            serde_json::json!({"title": "T"})
        );
    }

    #[test]
    fn placeholder_marker_is_read_from_metadata() {
        let raw = serde_json::json!({
            "case_id": "x", "title": "Case x", "description": null, "fir_number": null,
            "status": "ACTIVE", "investigator_id": null, "metadata": {"storage": "filesystem"},
            "created_at": "2026-11-21T00:00:00Z", "updated_at": "2026-11-21T00:00:00Z"
        });
        let record = CaseRecord::from_value("u", raw).unwrap();
        assert!(record.dto.has_filesystem_placeholder_marker());
    }

    #[test]
    fn wrong_case_shape_is_a_bad_response() {
        let err = CaseRecord::from_value("u", serde_json::json!({"id": 1})).unwrap_err();
        assert_eq!(err.exit_code(), 6);
    }
}
