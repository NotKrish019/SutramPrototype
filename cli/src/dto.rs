//! Client-side mirrors of the Rust API's wire types, plus identifier validation.
//!
//! These are deliberately independent copies: the CLI shares no code with `backend-rust`.
//! Sources:
//! * `HealthResponse`, `ReadinessResponse`: `backend-rust/src/api/routes/health.rs`
//! * `CaseDto`, `CreateCaseRequest`: `backend-rust/src/api/routes/cases.rs`
//! * `EvidenceReceipt`: `EvidenceUploadReceipt` in `backend-rust/src/ingestion/model.rs`
//! * `ExtractionRunSummary`, `UploadAndExtractResponse`: `backend-rust/src/extraction/model.rs`
//! * `EvidenceUpload`: multipart fields read by `upload_evidence` in
//!   `backend-rust/src/api/routes/evidence.rs`
//! * `TriggerReconstructionRequest`: `backend-rust/src/api/routes/reconstruction.rs`
//! * `ReconstructionResult` and its parts: `FullCaseReconstructionResult` in
//!   `backend-rust/src/reconstruction/service.rs`, field types in `reconstruction/model.rs`
//! * `CaseReport`: `CaseForensicReport` in `backend-rust/src/reconstruction/report.rs`
//!
//! The reconstruction mirrors only model the fields the CLI displays. Unmodelled fields are
//! ignored when parsing and kept in the raw body.
//!
//! JSON output always echoes the server's raw body, so fields the CLI does not model are
//! never dropped.

use serde::{Deserialize, Serialize};
