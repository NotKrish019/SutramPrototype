/// `FullCaseReconstructionResult`.
///
/// The current API always serializes `export_safeguard`. It is optional here only so that a
/// response without it is reported as "not reported" instead of being given a value.
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct ReconstructionResult {
    pub case_id: Option<String>,
    pub timeline: TimelineDto,
    pub spatial: SpatialDto,
    pub contradictions: ContradictionsDto,
    #[serde(default)]
    pub export_safeguard: Option<ExportSafeguardDto>,
}

impl ReconstructionResult {
    /// Every labelled assumption on the timeline with the event it belongs to, in API order.
    pub fn assumptions(&self) -> Vec<(&str, &AssumptionDto)> {
        self.timeline
            .entries
            .iter()
            .flat_map(|e| e.assumptions.iter().map(move |a| (e.event_id.as_str(), a)))
            .collect()
    }

    /// Number of movement segments over all trajectories.
    pub fn movement_segment_count(&self) -> usize {
        self.spatial
            .trajectories
            .iter()
            .map(|t| t.segments.len())
            .sum()
    }

    /// Movement segments the API marked as exceeding its configured speed threshold.
    pub fn flagged_speed_segment_count(&self) -> usize {
        self.spatial
            .trajectories
            .iter()
            .flat_map(|t| &t.segments)
            .filter(|s| s.transit_metrics.exceeds_configured_speed_threshold)
            .count()
    }
}

