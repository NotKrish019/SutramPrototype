/// `CaseDto` as serialized by the API. `created_at`/`updated_at` are RFC 3339 strings.
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct CaseDto {
    pub case_id: String,
    pub title: String,
    pub description: Option<String>,
    pub fir_number: Option<String>,
    pub status: String,
    pub investigator_id: Option<String>,
    pub metadata: Value,
    pub created_at: String,
    pub updated_at: String,
}

impl CaseDto {
    /// True when the record carries the marker the API puts on filesystem placeholder cases
    /// (storage folders without `case.json`): `metadata = {"storage": "filesystem"}`.
    /// Their title and timestamps are generated by the API at request time.
    pub fn has_filesystem_placeholder_marker(&self) -> bool {
        self.metadata.get("storage").and_then(Value::as_str) == Some("filesystem")
    }
}

/// A case exactly as returned (`raw`) plus its typed view (`dto`).
#[derive(Debug, Clone, PartialEq)]
pub struct CaseRecord {
    pub raw: Value,
    pub dto: CaseDto,
}

impl CaseRecord {
    /// Validates that `raw` has the `CaseDto` shape.
    pub fn from_value(url: &str, raw: Value) -> Result<Self, CliError> {
        let dto =
            serde_json::from_value::<CaseDto>(raw.clone()).map_err(|e| CliError::BadResponse {
                url: url.to_string(),
                reason: format!("case record does not match CaseDto ({e})"),
            })?;
        Ok(Self { raw, dto })
    }
}

