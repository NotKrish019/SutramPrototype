/// Counts read from a reconstruction response. Nothing here is computed beyond counting.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ReconstructionSummary {
    pub timeline_total_events: u64,
    pub timeline_strictly_ordered: u64,
    pub timeline_concurrent_uncertain: u64,
    pub timeline_excluded_events: usize,
    pub timeline_overlap_pairs: usize,
    pub spatial_trajectories: usize,
    pub spatial_movement_segments: usize,
    pub spatial_segments_exceeding_speed_threshold: usize,
    pub spatial_overlaps: usize,
    pub contradiction_leads: usize,
    pub contradiction_evaluated_segments: u64,
    pub contradiction_flagged_segments: u64,
    pub assumptions: usize,
    pub events_with_assumptions: usize,
}

impl ReconstructionSummary {
    pub fn of(r: &ReconstructionResult) -> Self {
        Self {
            timeline_total_events: r.timeline.total_events,
            timeline_strictly_ordered: r.timeline.strictly_ordered_count,
            timeline_concurrent_uncertain: r.timeline.concurrent_uncertain_count,
            timeline_excluded_events: r.timeline.excluded_events.len(),
            timeline_overlap_pairs: r.timeline.overlaps.len(),
            spatial_trajectories: r.spatial.trajectories.len(),
            spatial_movement_segments: r.movement_segment_count(),
            spatial_segments_exceeding_speed_threshold: r.flagged_speed_segment_count(),
            spatial_overlaps: r.spatial.overlaps.len(),
            contradiction_leads: r.contradictions.leads.len(),
            contradiction_evaluated_segments: r.contradictions.total_evaluated_segments,
            contradiction_flagged_segments: r.contradictions.flagged_segments_count,
            assumptions: r.assumptions().len(),
            events_with_assumptions: r
                .timeline
                .entries
                .iter()
                .filter(|e| !e.assumptions.is_empty())
                .count(),
        }
    }
}

/// Validates `--case` and checks the case exists. `action` completes "Nothing was ...".
async fn preflight(
    args: &ReconstructionArgs,
    client: &ApiClient,
    json: bool,
    action: &str,
) -> Result<(CaseId, CaseRecord), Rendered> {
    let case_id = CaseId::parse(&args.case_id, "--case")
        .map_err(|e| render_error_with_notes(&e, json, &[]))?;
    match client.get_case(&case_id).await {
        Ok(case) => Ok((case_id, case)),
        Err(err) => {
            let note = format!(
                "Nothing was {action}: the case check for {} failed.",
                case_id.as_str()
            );
            Err(render_error_with_notes(&err, json, &[note]))
        }
    }
}

/// Warnings about the case and the reconstruction's identity and content.
fn reconstruction_warnings(
    case_id: &CaseId,
    case: &CaseRecord,
    result: &ReconstructionResult,
) -> Vec<String> {
    let mut warnings = Vec::new();
    if case.dto.has_filesystem_placeholder_marker() {
        warnings.push(format!(
            "Case {} is a filesystem placeholder record (metadata.storage = \"filesystem\"), not a registered case.",
            case_id.as_str()
        ));
    }
    match result.case_id.as_deref() {
        None => warnings.push(
            "The reconstruction response does not name a case_id, so it cannot be matched to the requested case.".to_string(),
        ),
        Some(server) if !server.eq_ignore_ascii_case(case_id.as_str()) => warnings.push(format!(
            "The reconstruction response names case_id {server:?}, not the requested case {}.",
            case_id.as_str()
        )),
        Some(_) => {}
    }
    if result.timeline.total_events == 0 {
        warnings.push("The reconstruction contains no timeline events.".to_string());
    }
    if result.export_safeguard.is_none() {
        warnings.push(
            "The response has no export_safeguard; the export status is unknown, not clear."
                .to_string(),
        );
    }
    warnings
}

fn row(out: &mut String, label: &str, value: &str) {
    out.push_str(&format!("{label:<18}{value}\n"));
}

/// A [`row`] indented under a section heading, with its value column kept aligned.
fn sub_row(out: &mut String, label: &str, value: &str) {
    out.push_str(&format!("  {label:<18}{value}\n"));
}

fn server_case_id(result: &ReconstructionResult) -> String {
    result
        .case_id
        .clone()
        .unwrap_or_else(|| "not returned by the API".to_string())
}

/// The headline counts and the export safeguard.
pub fn render_summary(result: &ReconstructionResult) -> String {
    let s = ReconstructionSummary::of(result);
    let mut out = String::new();
    row(&mut out, "Case ID (server)", &server_case_id(result));
    row(
        &mut out,
        "Timeline",
        &format!(
            "{} event(s): {} strictly ordered, {} concurrent/uncertain; {} excluded; {} overlapping pair(s)",
            s.timeline_total_events,
            s.timeline_strictly_ordered,
            s.timeline_concurrent_uncertain,
            s.timeline_excluded_events,
            s.timeline_overlap_pairs
        ),
    );
    row(
        &mut out,
        "Spatial",
        &format!(
            "{} trajectory(ies), {} movement segment(s) ({} exceed the configured speed threshold), {} spatial-temporal overlap(s)",
            s.spatial_trajectories,
            s.spatial_movement_segments,
            s.spatial_segments_exceeding_speed_threshold,
            s.spatial_overlaps
        ),
    );
    row(
        &mut out,
        "Contradictions",
        &format!(
            "{} lead(s) from {} evaluated segment(s), {} flagged",
            s.contradiction_leads,
            s.contradiction_evaluated_segments,
            s.contradiction_flagged_segments
        ),
    );
    row(
        &mut out,
        "Assumptions",
        &format!(
            "{} labelled assumption(s) on {} event(s)",
            s.assumptions, s.events_with_assumptions
        ),
    );
    out.push_str(&render_export_safeguard(result));
    out
}

fn render_export_safeguard(result: &ReconstructionResult) -> String {
    let mut out = String::new();
    match &result.export_safeguard {
        None => row(
            &mut out,
            "Export safeguard",
            "NOT REPORTED by the API (unknown)",
        ),
        Some(gate) => {
            row(&mut out, "Export safeguard", &gate.status);
            for reason in &gate.reasons {
                out.push_str(&format!("  - {reason}\n"));
            }
        }
    }
    out
}

/// Assumptions grouped by identical (kind, field, value, basis), in first-seen order.
pub fn group_assumptions(result: &ReconstructionResult) -> Vec<(&AssumptionDto, Vec<&str>)> {
    let mut groups: Vec<(&AssumptionDto, Vec<&str>)> = Vec::new();
    for (event_id, assumption) in result.assumptions() {
        match groups.iter_mut().find(|(a, _)| *a == assumption) {
            Some((_, events)) => events.push(event_id),
            None => groups.push((assumption, vec![event_id])),
        }
    }
    groups
}

fn render_assumptions(result: &ReconstructionResult, list_events: bool) -> String {
    let groups = group_assumptions(result);
    if groups.is_empty() {
        return "\nAssumptions: none labelled by the API.\n".to_string();
    }
    let mut out = String::from("\nAssumptions (values the API used that were not observed):\n");
    for (a, events) in groups {
        out.push_str(&format!(
            "  - {}: {} = {:?} on {} event(s)\n      basis: {}\n",
            a.kind,
            a.field,
            a.assumed_value,
            events.len(),
            a.basis
        ));
        if list_events {
            out.push_str(&format!("      events: {}\n", events.join(", ")));
        }
    }
    out
}

fn render_excluded(result: &ReconstructionResult) -> String {
    let excluded = &result.timeline.excluded_events;
    if excluded.is_empty() {
        return String::new();
    }
    let mut out = String::from("\nExcluded events (not placed on the timeline):\n");
    for e in excluded {
        out.push_str(&format!(
            "  - {} (evidence {}): {}\n",
            e.event_id, e.source_evidence_id, e.reason
        ));
    }
    out
}

fn render_leads(result: &ReconstructionResult, detailed: bool) -> String {
    let c = &result.contradictions;
    let mut out = String::new();
    if c.leads.is_empty() {
        out.push_str("\nContradiction leads: none returned.\n");
    } else {
        out.push_str("\nContradiction leads (investigative leads, not findings):\n");
        for lead in &c.leads {
            out.push_str(&format!(
                "  - {} {} entity {}: event {} -> event {}\n",
                lead.lead_id, lead.lead_type, lead.entity_id, lead.event_a_id, lead.event_b_id
            ));
            if detailed {
                out.push_str(&format!(
                    "      explanation: {}\n",
                    lead.neutral_explanation
                ));
                out.push_str(&format!("      generated:   {}\n", lead.generated_at));
                if lead.limitations.is_empty() {
                    out.push_str("      limitations: none stated by the API\n");
                } else {
                    out.push_str("      limitations:\n");
                    for l in &lead.limitations {
                        out.push_str(&format!("        * {l}\n"));
                    }
                }
            }
        }
    }
    out.push_str(&format!("  Disclaimer: {}\n", c.disclaimer));
    out
}

fn render_limitations(limitations: &[&str]) -> String {
    let mut out = String::from("\nAPI limitations:\n");
    for l in limitations {
        out.push_str(&format!("  - {l}\n"));
    }
    out
}

