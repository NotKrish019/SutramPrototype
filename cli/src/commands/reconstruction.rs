//! `yukti reconstruction run | explain | compare`.
//!
//! API contracts (`backend-rust/src/api/routes/reconstruction.rs`, registered in `backend-rust/src/app.rs`):
//! * `GET  /api/v1/cases/:case_id` is the case preflight. The reconstruction and report handlers
//!   do not check that the case exists (an unknown case gets an empty reconstruction), so the CLI
//!   checks first and stops on any failure.
//! * `POST /api/v1/cases/:case_id/reconstruction` takes an optional `TriggerReconstructionRequest`
//!   and returns `200` with a `FullCaseReconstructionResult`. The CLI sends `{}`: default options,
//!   events loaded by the API from its own stores. It never sends options or events.
//! * `GET  /api/v1/cases/:case_id/reconstruction` returns the latest stored result, or computes
//!   one on the fly with default options (without storing it). The response does not say which.
//! * `GET  /api/v1/cases/:case_id/report` returns a `CaseForensicReport`, generated per request.
//! * Scenario comparison has no API endpoint, so `compare` sends nothing and exits 69.
//!
//! Forensic rules: the CLI only counts and displays what the API returned. It does not compute
//! findings, confidence or robustness, and it never fabricates a run ID, events or options.

