//! `yukti reconstruction run | explain | compare`.
//!
//! API contracts (`backend-rust/src/api/routes/reconstruction.rs`, registered in `backend-rust/src/app.rs`):
//! * `GET  /api/v1/cases/:case_id` is the case preflight. The reconstruction and report handlers
//!   do not check that the case exists (an unknown case gets an empty reconstruction), so the CLI
//!   checks first and stops on any failure.
//! * `POST /api/v1/cases/:case_id/reconstruction` takes an optional `TriggerReconstructionRequest`
//!   and returns `200` with a `FullCaseReconstructionResult`. The CLI sends `{}`: default options,
//!   events loaded by the API from its own stores. It never sends options or events.
//! * `GET  /api/v1/cases/:case_id/reconstruction` returns the latest stored result, or computes
//!   one on the fly with default options (without storing it). The response does not say which.
//! * `GET  /api/v1/cases/:case_id/report` returns a `CaseForensicReport`, generated per request.
//! * Scenario comparison has no API endpoint, so `compare` sends nothing and exits 69.
//!
//! Forensic rules: the CLI only counts and displays what the API returned. It does not compute
//! findings, confidence or robustness, and it never fabricates a run ID, events or options.

use serde::Serialize;
use serde_json::Value;

use crate::cli::{ReconstructionArgs, ReconstructionCommand};
use crate::client::{case_reconstruction_path, case_report_path, ApiClient};
use crate::dto::{
    AssumptionDto, CaseId, CaseRecord, CaseReportRecord, ReconstructionRecord,
    ReconstructionResult, TriggerReconstructionRequest,
};
use crate::error::{exit, CliError, ErrorInfo};
use crate::output::{render_error_with_notes, render_warnings, to_json, Rendered};

/// Schema of the `reconstruction run` JSON document.
pub const RECONSTRUCTION_RUN_SCHEMA: &str = "yukti.cli.reconstruction_run/v1";
/// Schema of the `reconstruction explain` JSON document.
pub const RECONSTRUCTION_EXPLANATION_SCHEMA: &str = "yukti.cli.reconstruction_explanation/v1";

/// Feature name used in the `compare` unsupported error.
pub const COMPARE_FEATURE: &str = "reconstruction scenario comparison";

/// The API returns no run identifier.
pub const LIMITATION_NO_RUN_ID: &str = "The API does not return a reconstruction run ID, so none is shown. (When PostgreSQL is configured the API assigns one internally, but the response does not include it.)";
/// The API does not report whether the run was stored.
pub const LIMITATION_PERSISTENCE_NOT_REPORTED: &str = "The API does not report whether this result was stored. It saves it on a best-effort basis (derived filesystem store, and PostgreSQL when configured) and returns HTTP 200 even if saving fails.";
/// What `run` asked the API to do.
pub const LIMITATION_DEFAULT_OPTIONS: &str = "The CLI sent no options, event candidates or raw events: the API used its default reconstruction options and the events it loaded from its own stores.";
/// `GET .../reconstruction` provenance is not reported.
pub const LIMITATION_PROVENANCE_UNKNOWN: &str = "The API returns its latest stored reconstruction for this case if it has one; otherwise it computes one on the fly with default options and does not store it. The response does not say which happened, so this is not necessarily a persisted reconstruction run.";
/// The report is generated by a second, independent request.
pub const LIMITATION_REPORT_SEPARATE: &str = "The judicial report is generated by a separate request, for which the API loads or recomputes the reconstruction again. A reconstruction run between the two requests could make them describe different results.";

/// Machine-readable provenance of an `explain` reconstruction.
const PROVENANCE_UNKNOWN: &str = "unknown_stored_or_computed_on_the_fly";

/// Runs a `reconstruction` subcommand.
pub async fn run(command: &ReconstructionCommand, client: &ApiClient, json: bool) -> Rendered {
    match command {
        ReconstructionCommand::Run(args) => run_reconstruction(args, client, json).await,
        ReconstructionCommand::Explain(args) => explain(args, client, json).await,
        ReconstructionCommand::Compare(args) => compare(args, json),
    }
}

