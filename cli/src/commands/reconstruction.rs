fn compare(args: &ReconstructionArgs, json: bool) -> Rendered {
    if let Err(err) = CaseId::parse(&args.case_id, "--case") {
        return render_error_with_notes(&err, json, &[]);
    }
    let err = CliError::Unsupported {
        feature: COMPARE_FEATURE.to_string(),
    };
    let notes = [
        "No request was sent to the API and the active reconstruction was not changed.".to_string(),
        "Scenario comparison awaits Swastik's backend scenario-comparison API; its contract has not been agreed yet.".to_string(),
    ];
    render_error_with_notes(&err, json, &notes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn assumption(kind: &str, value: &str) -> Value {
        json!({"kind": kind, "field": "source_timezone", "assumed_value": value, "basis": "default"})
    }

    fn entry(id: &str, assumptions: Vec<Value>) -> Value {
        json!({
            "event_id": id, "source_evidence_id": "ev", "raw_timestamp": "t",
            "time_window": {
                "nominal_utc": "2026-11-10T16:15:12Z", "precision": "EXACT_SECOND",
                "window_start_utc": "2026-11-10T16:15:12Z", "window_end_utc": "2026-11-10T16:15:13Z",
                "uncertainty_span_seconds": 1.0, "source_timezone": "UTC", "clock_offset_seconds": 0.0
            },
            "entity_ids": [], "metadata": {}, "ordering_status": "STRICTLY_ORDERED",
            "concurrent_event_ids": [], "assumptions": assumptions
        })
    }

    fn result(entries: Vec<Value>) -> ReconstructionResult {
        serde_json::from_value(json!({
            "case_id": "c",
            "timeline": {"total_events": entries.len(), "entries": entries, "overlaps": [],
                         "strictly_ordered_count": 0, "concurrent_uncertain_count": 0},
            "spatial": {"trajectories": [], "overlaps": []},
            "contradictions": {"leads": [], "total_evaluated_segments": 0,
                               "flagged_segments_count": 0, "disclaimer": "d"},
            "export_safeguard": {"status": "CLEAR", "reasons": []}
        }))
        .unwrap()
    }

    #[test]
    fn identical_assumptions_are_grouped_in_first_seen_order() {
        let r = result(vec![
            entry(
                "e1",
                vec![assumption("TIMEZONE_NOT_DECLARED_ON_EVENT", "UTC")],
            ),
            entry(
                "e2",
                vec![
                    assumption("TIMEZONE_NOT_DECLARED_ON_EVENT", "UTC"),
                    assumption("PRECISION_DEFAULTED", "EXACT_SECOND"),
                ],
            ),
            entry("e3", vec![]),
        ]);
        let groups = group_assumptions(&r);
        assert_eq!(groups.len(), 2);
        assert_eq!(groups[0].0.kind, "TIMEZONE_NOT_DECLARED_ON_EVENT");
        assert_eq!(groups[0].1, ["e1", "e2"]);
        assert_eq!(groups[1].1, ["e2"]);
        let s = ReconstructionSummary::of(&r);
        assert_eq!((s.assumptions, s.events_with_assumptions), (3, 2));
    }

    #[test]
    fn a_missing_export_safeguard_is_reported_as_unknown_not_clear() {
        let mut r = result(vec![]);
        r.export_safeguard = None;
        let text = render_summary(&r, &Ui::plain());
        assert!(text.contains("NOT REPORTED"), "{text}");
        assert!(!text.contains("CLEAR"), "{text}");
    }

    #[test]
    fn timeouts_warn_that_the_run_may_still_complete() {
        let id = CaseId::parse("3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c", "--case").unwrap();
        let notes = run_failure_notes(
            &CliError::Timeout {
                url: "u".into(),
                timeout: std::time::Duration::from_secs(1),
            },
            &id,
        );
        assert!(notes[0].contains("may still complete"));
        assert!(run_failure_notes(&crate::error::http_error("u", 404, ""), &id).is_empty());
    }
}
