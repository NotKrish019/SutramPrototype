#[derive(Serialize)]
struct ReconstructionSection<'a> {
    request: RequestDoc<'a>,
    /// The API does not report whether the result was stored or computed on the fly.
    provenance: &'static str,
    server_case_id: Option<&'a str>,
    /// Counted by the CLI from `response`.
    summary: ReconstructionSummary,
    response: &'a Value,
}

#[derive(Serialize)]
struct ReportSection<'a> {
    request: RequestDoc<'a>,
    /// The complete report body, or `null` when the request failed.
    response: Option<&'a Value>,
    /// Why the report is unavailable, or `null`.
    error: Option<ErrorInfo>,
}

#[derive(Serialize)]
struct ExplanationDocument<'a> {
    schema: &'static str,
    api_url: &'a str,
    case_id: &'a str,
    /// `false` when the report could not be retrieved (the exit code is then non-zero).
    complete: bool,
    reconstruction: ReconstructionSection<'a>,
    report: ReportSection<'a>,
    api_limitations: &'a [&'a str],
    warnings: &'a [String],
}

const EXPLAIN_LIMITATIONS: [&str; 3] = [
    LIMITATION_PROVENANCE_UNKNOWN,
    LIMITATION_NO_RUN_ID,
    LIMITATION_REPORT_SEPARATE,
];

async fn explain(args: &ReconstructionArgs, client: &ApiClient, json: bool) -> Rendered {
    let (case_id, case) = match preflight(args, client, json, "requested").await {
        Ok(found) => found,
        Err(rendered) => return rendered,
    };
    let record = match client.get_reconstruction(&case_id).await {
        Ok(record) => record,
        Err(err) => {
            let note = "The judicial report was not requested because the reconstruction could not be retrieved.".to_string();
            return render_error_with_notes(&err, json, &[note]);
        }
    };
    let report = client.get_case_report(&case_id).await;

    let mut warnings = reconstruction_warnings(&case_id, &case, &record.dto);
    if let Ok(report) = &report {
        warnings.extend(report_warnings(&case_id, &record, report));
    }
    let exit_code = match &report {
        Ok(_) => exit::SUCCESS,
        Err(err) => err.exit_code(),
    };
    let reconstruction_path = case_reconstruction_path(&case_id);
    let report_path = case_report_path(&case_id);

    if json {
        let doc = ExplanationDocument {
            schema: RECONSTRUCTION_EXPLANATION_SCHEMA,
            api_url: client.base_url(),
            case_id: case_id.as_str(),
            complete: report.is_ok(),
            reconstruction: ReconstructionSection {
                request: RequestDoc {
                    method: "GET",
                    path: &reconstruction_path,
                    body: None,
                },
                provenance: PROVENANCE_UNKNOWN,
                server_case_id: record.dto.case_id.as_deref(),
                summary: ReconstructionSummary::of(&record.dto),
                response: &record.raw,
            },
            report: ReportSection {
                request: RequestDoc {
                    method: "GET",
                    path: &report_path,
                    body: None,
                },
                response: report.as_ref().ok().map(|r| &r.raw),
                error: report.as_ref().err().map(ErrorInfo::from),
            },
            api_limitations: &EXPLAIN_LIMITATIONS,
            warnings: &warnings,
        };
        return Rendered::stdout(to_json(&doc), exit_code);
    }

    let mut stdout = render_explanation(&case_id, &reconstruction_path, &record.dto);
    stdout.push_str(&render_report(&report_path, &report));
    stdout.push_str(&render_limitations(&EXPLAIN_LIMITATIONS));
    let mut stderr = render_warnings(&warnings);
    if let Err(err) = &report {
        stderr.push_str(&format!(
            "error: the judicial report is unavailable: {err}\nnote: The reconstruction above was retrieved; only the report is missing.\n"
        ));
    }
    Rendered {
        stdout,
        stderr,
        exit_code,
    }
}

/// Differences between the report and the reconstruction retrieved just before it.
pub fn report_warnings(
    case_id: &CaseId,
    reconstruction: &ReconstructionRecord,
    report: &CaseReportRecord,
) -> Vec<String> {
    let r = &reconstruction.dto;
    let rep = &report.dto;
    let mut warnings = Vec::new();
    if !rep.case_id.eq_ignore_ascii_case(case_id.as_str()) {
        warnings.push(format!(
            "The report names case_id {:?}, not the requested case {}.",
            rep.case_id,
            case_id.as_str()
        ));
    }
    let checks = [
        (
            "timeline events",
            rep.summary.total_timeline_events,
            r.timeline.total_events,
        ),
        (
            "excluded events",
            rep.summary.excluded_events_count,
            r.timeline.excluded_events.len() as u64,
        ),
        (
            "contradiction leads",
            rep.summary.open_contradictions_count,
            r.contradictions.leads.len() as u64,
        ),
    ];
    for (what, in_report, in_reconstruction) in checks {
        if in_report != in_reconstruction {
            warnings.push(format!(
                "The report counts {in_report} {what} but the reconstruction shown has {in_reconstruction}; they may describe different results."
            ));
        }
    }
    warnings
}

/// Full human-readable reconstruction detail.
pub fn render_explanation(case_id: &CaseId, path: &str, result: &ReconstructionResult) -> String {
    let mut out = format!(
        "Reconstruction of case {} (GET {path} -> HTTP 200)\n",
        case_id.as_str()
    );
    row(
        &mut out,
        "Provenance",
        "UNKNOWN: stored result or computed on the fly (see API limitations)",
    );
    out.push_str(&render_summary(result));

    out.push_str("\nTimeline (in the API's order):\n");
    if result.timeline.entries.is_empty() {
        out.push_str("  no timeline entries returned\n");
    }
    for (i, e) in result.timeline.entries.iter().enumerate() {
        let w = &e.time_window;
        out.push_str(&format!(
            "  {:>3}. {}  {}  {}  event {}  evidence {}\n",
            i + 1,
            w.nominal_utc,
            w.precision,
            e.ordering_status,
            e.event_id,
            e.source_evidence_id
        ));
        out.push_str(&format!(
            "       window {} .. {} ({} s); timezone {}, clock offset {} s; raw {:?}\n",
            w.window_start_utc,
            w.window_end_utc,
            w.uncertainty_span_seconds,
            w.source_timezone,
            w.clock_offset_seconds,
            e.raw_timestamp
        ));
        if let Some(desc) = &e.raw_description {
            out.push_str(&format!("       description: {desc}\n"));
        }
        if !e.assumptions.is_empty() {
            let kinds: Vec<&str> = e.assumptions.iter().map(|a| a.kind.as_str()).collect();
            out.push_str(&format!("       assumptions: {}\n", kinds.join(", ")));
        }
    }

    out.push_str(&render_assumptions(result, true));
    out.push_str(&render_excluded(result));
    out.push_str(&render_spatial(result));
    out.push_str(&render_leads(result, true));
    out
}

fn render_spatial(result: &ReconstructionResult) -> String {
    let spatial = &result.spatial;
    if spatial.trajectories.is_empty() && spatial.overlaps.is_empty() {
        return "\nSpatial findings: none returned (no located events were reconstructed).\n"
            .to_string();
    }
    let mut out = String::from("\nSpatial findings:\n");
    for t in &spatial.trajectories {
        let max_speed = t
            .max_min_required_speed_kmh
            .map(|v| format!("{v:.3} km/h"))
            .unwrap_or_else(|| "not reported".to_string());
        out.push_str(&format!(
            "  - entity {}: {} waypoint(s), {} segment(s), {:.3} km total, max minimum required speed {max_speed}\n",
            t.entity_id,
            t.waypoints.len(),
            t.segments.len(),
            t.total_distance_km
        ));
        for s in &t.segments {
            let m = &s.transit_metrics;
            let speed = m
                .min_required_speed_kmh
                .map(|v| format!("{v:.3} km/h"))
                .unwrap_or_else(|| "n/a".to_string());
            out.push_str(&format!(
                "      {} -> {}: {:.3} km, min required {speed} vs threshold {} km/h: {}{}\n",
                s.origin_event_id,
                s.destination_event_id,
                m.distance_km,
                m.configured_speed_threshold_kmh,
                m.threshold_evaluation,
                if s.has_intervening_unlocated_events {
                    " (intervening unlocated events)"
                } else {
                    ""
                }
            ));
        }
    }
    for o in &spatial.overlaps {
        out.push_str(&format!(
            "  - overlap, entity {}: event {} and event {} at {:.3} km apart, co-located: {}\n",
            o.entity_id,
            o.event_a_id,
            o.event_b_id,
            o.distance_km,
            if o.is_co_located { "yes" } else { "no" }
        ));
    }
    out
}

fn render_report(path: &str, report: &Result<CaseReportRecord, CliError>) -> String {
    let mut out = String::from("\nJudicial report");
    match report {
        Err(err) => {
            out.push_str(&format!(" (GET {path}): UNAVAILABLE\n"));
            sub_row(&mut out, "Error", &err.to_string());
        }
        Ok(record) => {
            let r = &record.dto;
            out.push_str(&format!(" (GET {path} -> HTTP 200):\n"));
            sub_row(&mut out, "Report ID", &r.report_id);
            sub_row(&mut out, "Title", &r.title);
            sub_row(&mut out, "Generated", &r.generated_at);
            sub_row(
                &mut out,
                "Evidence items",
                &r.summary.evidence_count.to_string(),
            );
            sub_row(&mut out, "Judicial export", &r.judicial_export_status);
            sub_row(&mut out, "Reason", &r.judicial_export_reason);
            sub_row(&mut out, "Disclaimer", &r.forensic_disclaimer);
            out.push_str("\n----- Markdown forensic dossier (as returned by the API) -----\n");
            out.push_str(&r.markdown_dossier);
            if !r.markdown_dossier.ends_with('\n') {
                out.push('\n');
            }
            out.push_str("----- end of dossier -----\n");
        }
    }
    out
}

/* ------------------------------------------------------------------------------- compare */

fn compare(args: &ReconstructionArgs, json: bool) -> Rendered {
    if let Err(err) = CaseId::parse(&args.case_id, "--case") {
        return render_error_with_notes(&err, json, &[]);
    }
    let err = CliError::Unsupported {
        feature: COMPARE_FEATURE.to_string(),
    };
    let notes = [
        "No request was sent to the API and the active reconstruction was not changed.".to_string(),
        "Scenario comparison awaits Swastik's backend scenario-comparison API; its contract has not been agreed yet.".to_string(),
    ];
    render_error_with_notes(&err, json, &notes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn assumption(kind: &str, value: &str) -> Value {
        json!({"kind": kind, "field": "source_timezone", "assumed_value": value, "basis": "default"})
    }

    fn entry(id: &str, assumptions: Vec<Value>) -> Value {
        json!({
            "event_id": id, "source_evidence_id": "ev", "raw_timestamp": "t",
            "time_window": {
                "nominal_utc": "2026-11-10T16:15:12Z", "precision": "EXACT_SECOND",
                "window_start_utc": "2026-11-10T16:15:12Z", "window_end_utc": "2026-11-10T16:15:13Z",
                "uncertainty_span_seconds": 1.0, "source_timezone": "UTC", "clock_offset_seconds": 0.0
            },
            "entity_ids": [], "metadata": {}, "ordering_status": "STRICTLY_ORDERED",
            "concurrent_event_ids": [], "assumptions": assumptions
        })
    }

    fn result(entries: Vec<Value>) -> ReconstructionResult {
        serde_json::from_value(json!({
            "case_id": "c",
            "timeline": {"total_events": entries.len(), "entries": entries, "overlaps": [],
                         "strictly_ordered_count": 0, "concurrent_uncertain_count": 0},
            "spatial": {"trajectories": [], "overlaps": []},
            "contradictions": {"leads": [], "total_evaluated_segments": 0,
                               "flagged_segments_count": 0, "disclaimer": "d"},
            "export_safeguard": {"status": "CLEAR", "reasons": []}
        }))
        .unwrap()
    }

    #[test]
    fn identical_assumptions_are_grouped_in_first_seen_order() {
        let r = result(vec![
            entry(
                "e1",
                vec![assumption("TIMEZONE_NOT_DECLARED_ON_EVENT", "UTC")],
            ),
            entry(
                "e2",
                vec![
                    assumption("TIMEZONE_NOT_DECLARED_ON_EVENT", "UTC"),
                    assumption("PRECISION_DEFAULTED", "EXACT_SECOND"),
                ],
            ),
            entry("e3", vec![]),
        ]);
        let groups = group_assumptions(&r);
        assert_eq!(groups.len(), 2);
        assert_eq!(groups[0].0.kind, "TIMEZONE_NOT_DECLARED_ON_EVENT");
        assert_eq!(groups[0].1, ["e1", "e2"]);
        assert_eq!(groups[1].1, ["e2"]);
        let s = ReconstructionSummary::of(&r);
        assert_eq!((s.assumptions, s.events_with_assumptions), (3, 2));
    }

    #[test]
    fn a_missing_export_safeguard_is_reported_as_unknown_not_clear() {
        let mut r = result(vec![]);
        r.export_safeguard = None;
        let text = render_summary(&r);
        assert!(text.contains("NOT REPORTED"), "{text}");
        assert!(!text.contains("CLEAR"), "{text}");
    }

    #[test]
    fn timeouts_warn_that_the_run_may_still_complete() {
        let id = CaseId::parse("3f2b8c1e-7a4d-4e1b-9c3a-5d6e7f8a9b0c", "--case").unwrap();
        let notes = run_failure_notes(
            &CliError::Timeout {
                url: "u".into(),
                timeout: std::time::Duration::from_secs(1),
            },
            &id,
        );
        assert!(notes[0].contains("may still complete"));
        assert!(run_failure_notes(&crate::error::http_error("u", 404, ""), &id).is_empty());
    }
}
