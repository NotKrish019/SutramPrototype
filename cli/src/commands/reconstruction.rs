#[derive(Serialize)]
struct RequestDoc<'a> {
    method: &'static str,
    path: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    body: Option<&'a TriggerReconstructionRequest>,
}

#[derive(Serialize)]
struct RunDocument<'a> {
    schema: &'static str,
    api_url: &'a str,
    /// The case requested on the command line (canonical UUID).
    case_id: &'a str,
    /// `case_id` exactly as returned in the response (`null` when absent).
    server_case_id: Option<&'a str>,
    request: RequestDoc<'a>,
    /// Counted by the CLI from `response`.
    summary: ReconstructionSummary,
    /// `export_safeguard` exactly as returned (`null` when absent).
    export_safeguard: &'a Value,
    /// The complete response body, exactly as returned.
    response: &'a Value,
    api_limitations: &'a [&'a str],
    warnings: &'a [String],
}

const RUN_LIMITATIONS: [&str; 3] = [
    LIMITATION_NO_RUN_ID,
    LIMITATION_PERSISTENCE_NOT_REPORTED,
    LIMITATION_DEFAULT_OPTIONS,
];

async fn run_reconstruction(args: &ReconstructionArgs, client: &ApiClient, json: bool) -> Rendered {
    let (case_id, case) = match preflight(args, client, json, "reconstructed").await {
        Ok(found) => found,
        Err(rendered) => return rendered,
    };
    let request = TriggerReconstructionRequest::default();
    let record = match client.run_reconstruction(&case_id, &request).await {
        Ok(record) => record,
        Err(err) => {
            let notes = run_failure_notes(&err, &case_id);
            return render_error_with_notes(&err, json, &notes);
        }
    };
    let result = &record.dto;
    let warnings = reconstruction_warnings(&case_id, &case, result);
    let path = case_reconstruction_path(&case_id);

    if json {
        let doc = RunDocument {
            schema: RECONSTRUCTION_RUN_SCHEMA,
            api_url: client.base_url(),
            case_id: case_id.as_str(),
            server_case_id: result.case_id.as_deref(),
            request: RequestDoc {
                method: "POST",
                path: &path,
                body: Some(&request),
            },
            summary: ReconstructionSummary::of(result),
            export_safeguard: record.raw.get("export_safeguard").unwrap_or(&Value::Null),
            response: &record.raw,
            api_limitations: &RUN_LIMITATIONS,
            warnings: &warnings,
        };
        return Rendered::stdout(to_json(&doc), exit::SUCCESS);
    }

    let mut out = format!(
        "Reconstruction completed for case {} (POST {path} -> HTTP 200)\n",
        case_id.as_str()
    );
    row(&mut out, "Run ID", "not returned by the API");
    out.push_str(&render_summary(result));
    out.push_str(&render_assumptions(result, false));
    out.push_str(&render_excluded(result));
    out.push_str(&render_leads(result, false));
    out.push_str(&render_limitations(&RUN_LIMITATIONS));
    out.push_str(&format!(
        "\nRun `yukti reconstruction explain --case {}` for the full detail and the judicial report.\n",
        case_id.as_str()
    ));
    Rendered {
        stdout: out,
        stderr: render_warnings(&warnings),
        exit_code: exit::SUCCESS,
    }
}

/// Extra guidance for a failed reconstruction request (human mode only).
pub fn run_failure_notes(err: &CliError, case_id: &CaseId) -> Vec<String> {
    match err {
        CliError::Timeout { .. } => vec![format!(
            "The API may still complete and store the reconstruction for case {} after the CLI stopped waiting. Retry with a larger --timeout, or check with `yukti reconstruction explain`.",
            case_id.as_str()
        )],
        CliError::Http { status, .. } if *status >= 500 => vec![
            "The API reported a server error; no reconstruction result was returned.".to_string(),
        ],
        _ => Vec::new(),
    }
}

