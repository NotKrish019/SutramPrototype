#[derive(Serialize)]
struct RequestDoc<'a> {
    method: &'static str,
    path: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    body: Option<&'a TriggerReconstructionRequest>,
}

#[derive(Serialize)]
struct RunDocument<'a> {
    schema: &'static str,
    api_url: &'a str,
    /// The case requested on the command line (canonical UUID).
    case_id: &'a str,
    /// `case_id` exactly as returned in the response (`null` when absent).
    server_case_id: Option<&'a str>,
    request: RequestDoc<'a>,
    /// Counted by the CLI from `response`.
    summary: ReconstructionSummary,
    /// `export_safeguard` exactly as returned (`null` when absent).
    export_safeguard: &'a Value,
    /// The complete response body, exactly as returned.
    response: &'a Value,
    api_limitations: &'a [&'a str],
    warnings: &'a [String],
}

const RUN_LIMITATIONS: [&str; 3] = [
    LIMITATION_NO_RUN_ID,
    LIMITATION_PERSISTENCE_NOT_REPORTED,
    LIMITATION_DEFAULT_OPTIONS,
];

async fn run_reconstruction(
    args: &ReconstructionArgs,
    client: &ApiClient,
    json: bool,
    ui: &Ui,
) -> Rendered {
    let (case_id, case) = match preflight(args, client, json, "reconstructed").await {
        Ok(found) => found,
        Err(rendered) => return rendered,
    };
    let request = TriggerReconstructionRequest::default();
    let record = match client.run_reconstruction(&case_id, &request).await {
        Ok(record) => record,
        Err(err) => {
            let notes = run_failure_notes(&err, &case_id);
            return render_error_with_notes(&err, json, &notes);
        }
    };
    let result = &record.dto;
    let warnings = reconstruction_warnings(&case_id, &case, result);
    let path = case_reconstruction_path(&case_id);

    if json {
        let doc = RunDocument {
            schema: RECONSTRUCTION_RUN_SCHEMA,
            api_url: client.base_url(),
            case_id: case_id.as_str(),
            server_case_id: result.case_id.as_deref(),
            request: RequestDoc {
                method: "POST",
                path: &path,
                body: Some(&request),
            },
            summary: ReconstructionSummary::of(result),
            export_safeguard: record.raw.get("export_safeguard").unwrap_or(&Value::Null),
            response: &record.raw,
            api_limitations: &RUN_LIMITATIONS,
            warnings: &warnings,
        };
        return Rendered::stdout(to_json(&doc), exit::SUCCESS);
    }

    let mut out = ui.header(&["reconstruction", "run"], client.base_url());
    out.push('\n');
    out.push_str(&format!(
        "{MARGIN}{}  {}\n",
        ui.badge(Badge::Ok, "completed"),
        ui.paint(
            Tone::Text,
            &format!("Reconstruction completed for case {}", case_id.as_str())
        )
    ));
    out.push_str(&format!(
        "{MARGIN}{}\n",
        ui.paint(
            Tone::Subtle,
            &format!(
                "POST {path} {} HTTP 200 {} run ID not returned by the API",
                ui.g(Glyph::Arrow),
                ui.g(Glyph::Dot)
            )
        )
    ));
    out.push_str(&render_summary(result, ui));
    out.push_str(&render_assumptions(result, false, ui));
    out.push_str(&render_excluded(&result.timeline, ui));
    out.push_str(&render_leads(&result.contradictions, false, ui));
    out.push_str(&render_limitations(&RUN_LIMITATIONS, ui));
    out.push('\n');
    out.push_str(&ui.legend());
    out.push('\n');
    let id = case_id.as_str();
    out.push_str(&ui.next(
        "full detail",
        &format!("yukti reconstruction explain --case {id}"),
    ));
    out.push_str(&ui.next("timeline", &format!("yukti timeline --case {id}")));
    out.push_str(&ui.next("provenance", &format!("yukti provenance --case {id}")));
    Rendered {
        stdout: out,
        stderr: render_warnings(&warnings),
        exit_code: exit::SUCCESS,
    }
}

/// Extra guidance for a failed reconstruction request (human mode only).
pub fn run_failure_notes(err: &CliError, case_id: &CaseId) -> Vec<String> {
    match err {
        CliError::Timeout { .. } => vec![format!(
            "The API may still complete and store the reconstruction for case {} after the CLI stopped waiting. Retry with a larger --timeout, or check with `yukti reconstruction explain`.",
            case_id.as_str()
        )],
        CliError::Http { status, .. } if *status >= 500 => vec![
            "The API reported a server error; no reconstruction result was returned.".to_string(),
        ],
        _ => Vec::new(),
    }
}

/* ------------------------------------------------------------------------------- explain */

#[derive(Serialize)]
struct ReconstructionSection<'a> {
    request: RequestDoc<'a>,
    /// The API does not report whether the result was stored or computed on the fly.
    provenance: &'static str,
    server_case_id: Option<&'a str>,
    /// Counted by the CLI from `response`.
    summary: ReconstructionSummary,
    response: &'a Value,
}

#[derive(Serialize)]
struct ReportSection<'a> {
    request: RequestDoc<'a>,
    /// The complete report body, or `null` when the request failed.
    response: Option<&'a Value>,
    /// Why the report is unavailable, or `null`.
    error: Option<ErrorInfo>,
}

#[derive(Serialize)]
struct ExplanationDocument<'a> {
    schema: &'static str,
    api_url: &'a str,
    case_id: &'a str,
    /// `false` when the report could not be retrieved (the exit code is then non-zero).
    complete: bool,
    reconstruction: ReconstructionSection<'a>,
    report: ReportSection<'a>,
    api_limitations: &'a [&'a str],
    warnings: &'a [String],
}

const EXPLAIN_LIMITATIONS: [&str; 3] = [
    LIMITATION_PROVENANCE_UNKNOWN,
    LIMITATION_NO_RUN_ID,
    LIMITATION_REPORT_SEPARATE,
];

async fn explain(args: &ReconstructionArgs, client: &ApiClient, json: bool, ui: &Ui) -> Rendered {
    let (case_id, case) = match preflight(args, client, json, "requested").await {
        Ok(found) => found,
        Err(rendered) => return rendered,
    };
    let record = match client.get_reconstruction(&case_id).await {
        Ok(record) => record,
        Err(err) => {
            let note = "The judicial report was not requested because the reconstruction could not be retrieved.".to_string();
            return render_error_with_notes(&err, json, &[note]);
        }
    };
    let report = client.get_case_report(&case_id).await;

    let mut warnings = reconstruction_warnings(&case_id, &case, &record.dto);
    if let Ok(report) = &report {
        warnings.extend(report_warnings(&case_id, &record, report));
    }
    let exit_code = match &report {
        Ok(_) => exit::SUCCESS,
        Err(err) => err.exit_code(),
    };
    let reconstruction_path = case_reconstruction_path(&case_id);
    let report_path = case_report_path(&case_id);

    if json {
        let doc = ExplanationDocument {
            schema: RECONSTRUCTION_EXPLANATION_SCHEMA,
            api_url: client.base_url(),
            case_id: case_id.as_str(),
            complete: report.is_ok(),
            reconstruction: ReconstructionSection {
                request: RequestDoc {
                    method: "GET",
                    path: &reconstruction_path,
                    body: None,
                },
                provenance: PROVENANCE_UNKNOWN,
                server_case_id: record.dto.case_id.as_deref(),
                summary: ReconstructionSummary::of(&record.dto),
                response: &record.raw,
            },
            report: ReportSection {
                request: RequestDoc {
                    method: "GET",
                    path: &report_path,
                    body: None,
                },
                response: report.as_ref().ok().map(|r| &r.raw),
                error: report.as_ref().err().map(ErrorInfo::from),
            },
            api_limitations: &EXPLAIN_LIMITATIONS,
            warnings: &warnings,
        };
        return Rendered::stdout(to_json(&doc), exit_code);
    }

    let mut stdout = ui.header(&["reconstruction", "explain"], client.base_url());
    stdout.push_str(&render_explanation(
        &case_id,
        &reconstruction_path,
        &record.dto,
        ui,
    ));
    stdout.push_str(&render_report(&report_path, &report, ui));
    stdout.push_str(&render_limitations(&EXPLAIN_LIMITATIONS, ui));
    let mut stderr = render_warnings(&warnings);
    if let Err(err) = &report {
        stderr.push_str(&format!(
            "error: the judicial report is unavailable: {err}\nnote: The reconstruction above was retrieved; only the report is missing.\n"
        ));
    }
    Rendered {
        stdout,
        stderr,
        exit_code,
    }
}

/// Differences between the report and the reconstruction retrieved just before it.
pub fn report_warnings(
    case_id: &CaseId,
    reconstruction: &ReconstructionRecord,
    report: &CaseReportRecord,
) -> Vec<String> {
    let r = &reconstruction.dto;
    let rep = &report.dto;
    let mut warnings = Vec::new();
    if !rep.case_id.eq_ignore_ascii_case(case_id.as_str()) {
        warnings.push(format!(
            "The report names case_id {:?}, not the requested case {}.",
            rep.case_id,
            case_id.as_str()
        ));
    }
    let checks = [
        (
            "timeline events",
            rep.summary.total_timeline_events,
            r.timeline.total_events,
        ),
        (
            "excluded events",
            rep.summary.excluded_events_count,
            r.timeline.excluded_events.len() as u64,
        ),
        (
            "contradiction leads",
            rep.summary.open_contradictions_count,
            r.contradictions.leads.len() as u64,
        ),
    ];
    for (what, in_report, in_reconstruction) in checks {
        if in_report != in_reconstruction {
            warnings.push(format!(
                "The report counts {in_report} {what} but the reconstruction shown has {in_reconstruction}; they may describe different results."
            ));
        }
    }
    warnings
}

/// Full human-readable reconstruction detail.
pub fn render_explanation(
    case_id: &CaseId,
    path: &str,
    result: &ReconstructionResult,
    ui: &Ui,
) -> String {
    let mut out = String::from("\n");
    out.push_str(&format!(
        "{MARGIN}{}\n{MARGIN}{}\n",
        ui.bold(
            Tone::Strong,
            &format!("Reconstruction of case {}", case_id.as_str())
        ),
        ui.paint(
            Tone::Subtle,
            &format!("GET {path} {} HTTP 200", ui.g(Glyph::Arrow))
        )
    ));
    out.push_str(&format!(
        "{MARGIN}{} {}\n",
        ui.mark(Glyph::Assumed, Tone::Warn),
        ui.paint(
            Tone::Muted,
            "Provenance UNKNOWN: stored result or computed on the fly (see API limitations)"
        )
    ));
    out.push_str(&render_summary(result, ui));

    out.push_str(&ui.section(
        "Timeline",
        &format!(
            "{} entries, in the API's order",
            result.timeline.entries.len()
        ),
    ));
    if result.timeline.entries.is_empty() {
        out.push_str(&format!(
            "{MARGIN}{}\n",
            ui.paint(Tone::Muted, "no timeline entries returned")
        ));
    } else {
        let entries: Vec<&TimelineEntryDto> = result.timeline.entries.iter().collect();
        out.push_str(&render_timeline_rail(&entries, ui));
    }

    out.push_str(&render_assumptions(result, true, ui));
    out.push_str(&render_excluded(&result.timeline, ui));
    out.push_str(&render_spatial(&result.spatial, ui));
    out.push_str(&render_leads(&result.contradictions, true, ui));
    out
}

fn render_report(path: &str, report: &Result<CaseReportRecord, CliError>, ui: &Ui) -> String {
    let mut out = ui.section("Judicial report", &format!("GET {path}"));
    match report {
        Err(err) => {
            out.push_str(&ui.kv_painted("Status", &ui.badge(Badge::Flag, "unavailable")));
            out.push_str(&ui.kv("Error", Tone::Flag, &err.to_string()));
        }
        Ok(record) => {
            let r = &record.dto;
            out.push_str(&ui.kv("Report ID", Tone::Text, &r.report_id));
            out.push_str(&ui.kv("Title", Tone::Strong, &r.title));
            out.push_str(&ui.kv("Generated", Tone::Muted, &r.generated_at));
            out.push_str(&ui.kv(
                "Evidence items",
                Tone::Text,
                &r.summary.evidence_count.to_string(),
            ));
            out.push_str(&ui.kv_painted(
                "Judicial export",
                &ui.badge(
                    status_badge(&r.judicial_export_status),
                    &r.judicial_export_status,
                ),
            ));
            out.push_str(&ui.kv("Reason", Tone::Muted, &r.judicial_export_reason));
            out.push_str(&ui.kv("Disclaimer", Tone::Subtle, &r.forensic_disclaimer));
            out.push_str(&render_dossier(&r.markdown_dossier, ui));
        }
    }
    out
}

/// The markdown dossier, exactly as returned, between two rules.
pub fn render_dossier(markdown: &str, ui: &Ui) -> String {
    let rule = |label: &str| {
        let text = format!(" {label} ");
        let side = ui
            .width
            .saturating_sub(text.chars().count() + MARGIN.len() * 2)
            / 2;
        format!(
            "{MARGIN}{}{}{}\n",
            ui.paint(Tone::Line, &ui.g(Glyph::Rule).repeat(side)),
            ui.paint(Tone::Subtle, &text),
            ui.paint(Tone::Line, &ui.g(Glyph::Rule).repeat(side))
        )
    };
    let mut out = String::from("\n");
    out.push_str(&rule("Markdown forensic dossier (as returned by the API)"));
    out.push_str(markdown);
    if !markdown.ends_with('\n') {
        out.push('\n');
    }
    out.push_str(&rule("end of dossier"));
    out
}

